let listings = '# Localized Chrome and Edge listing copy\n\nGenerated by `bun run scripts/build-store-copy.ts`. Console updates must be verified separately; packaged translations do not update store descriptions. Apply v' + EXTENSION_VERSION + ' feature copy when that version is available in the corresponding store.\n\n';
for (const [code, c] of Object.entries(releaseLocales)) {
  const browserLocale = manifestLocale(code);
  if (!browserLocale) continue;
  const folder = `public/_locales/${browserLocale}`;
  const file = `${folder}/messages.json`;
  const old = existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : {};
  const t = LOCALES[code as keyof typeof LOCALES];
  const generated = `ChatGPT: ${t.content.shortcutsPopover.playPause} · ${t.content.tooltips.speed} · ${t.content.tooltips.download}`;
  const description = descriptions[code] || audience[code as keyof typeof audience]?.summary || (generated.length <= 132 ? generated : `ChatGPT: ${t.content.shortcutsPopover.playPause} · ${t.content.tooltips.download}`);
  if (!description || description.length > 132) throw new Error(`Invalid store summary: ${code}`);
  const newLocale = additionalLanguages.some(language => language.code === code);
  const title = (!newLocale && old.extensionName?.message) || 'ChatGPT Audio Controls — ' + t.content.tooltips.readAloud;
  mkdirSync(folder, { recursive: true });
  writeFileSync(file, JSON.stringify({ ...Object.fromEntries(Object.entries(commandLabels(code)).filter(([name]) => name !== 'toggle-floating-ui').map(([name, label]) => ['command_' + name.replaceAll('-', '_'), { message: label.replace('{s}', '↔') }])), extensionName: { message: title }, extensionDescription: { message: description }, extensionActionTitle: { message: 'ChatGPT Audio Controls' }, visibilityCommand: { message: c.visibilityShortcut } }, null, 2) + '\n');
  const f = featureCopy(code);
  const site = config.siteUrl + (code === 'en' ? '' : code + '/');
  listings += `## ${code}\n\n### Title\n\n${title}\n\n### Summary\n\n${description}\n\n### Description\n\n${c.siteIntro}\n\n${f.layout}: ${polishCopy(code).layoutDescription}\n${f.notify}.\n\n${c.quickStartBody}\n\n${c.compactHelp}\n\n${c.hideHint}\n${c.idleOnly} / ${c.allUi}\n\n${c.visibilityShortcut}: Alt+Shift+Y (Windows/Linux) / Option ⌥+Shift ⇧+Y (macOS). ${c.customize}.\n${c.shortcutScope}\n\n${c.sourceFormat}\n\n${c.desktop}\n\n${c.privacyBody}\n\n${c.feedbackPolicy}\n\n${c.independent}\n\n${c.website}: ${site}\n${c.help}: ${site}#help\n${c.privacy}: ${site}#privacy\n\n`;
}
writeFileSync('docs/STORE-LISTINGS.md', listings.trimEnd() + '\n');
