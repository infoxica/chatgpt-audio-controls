import config from '../config/release.json';
import { validFeedbackURL } from '../src/shared/feedback';
import { mkdirSync, copyFileSync, writeFileSync } from 'node:fs';
import { releaseLocales } from '../src/shared/i18n/release-copy';
import { SUPPORTED_LANGUAGES } from '../src/shared/constants';
mkdirSync('build/feedback', { recursive: true });
for (const file of ['Code.gs', 'Index.html', 'appsscript.json']) copyFileSync(`feedback/${file}`, `build/feedback/${file}`);
const names = Object.fromEntries(SUPPORTED_LANGUAGES.filter(item => item.code !== 'auto').map(item => [item.code, item.nativeName]));
if (!validFeedbackURL(config.feedbackUrl)) throw new Error('Configure the verified feedback Worker URL first.');
writeFileSync('build/feedback/Translations.gs', `// Generated from shared release copy.\nconst FEEDBACK_URL = ${JSON.stringify(config.feedbackUrl)};\nconst SURVEY_COPY = ${JSON.stringify(releaseLocales)};\nconst LANGUAGE_NAMES = ${JSON.stringify(names)};\n`);
console.log('Built Apps Script transition page in build/feedback.');
